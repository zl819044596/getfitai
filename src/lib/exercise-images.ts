const commonPrefixes = /^(?:dumbbell|db|barbell|bb|kettlebell|kb|cable|machine|bodyweight|bw|standing|seated|lying|overhead)\s+/i

export function getExerciseImage(name: string): string {
  if (!name) return exerciseImages.default

  const exactName = name.toLowerCase().trim().replace(/\s+/g, " ")
  if (exactName in exerciseImages) return exerciseImages[exactName]

  let normalizedName = exactName
  while (commonPrefixes.test(normalizedName)) {
    normalizedName = normalizedName.replace(commonPrefixes, "").trim()
  }

  if (normalizedName in exerciseImages) return exerciseImages[normalizedName]

  return exerciseImages.default
}
